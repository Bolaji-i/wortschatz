/** A word's usage tip in the interface language. */
export function tipText(usage: string) {
  if (lang.value === 'de') return usage
  return TIP_GLOSSARY.reduce((s, [re, en]) => s.replace(re, en), usage)
}

/** "1 Wort" / "5 Wörter" – "1 word" / "5 words" */
export function words(n: number) {
  return n === 1 ? t('wordOne') : t('wordMany')
}

export function levelName(l: Level) {
  return t(`lvl${l}` as Key)
}
export function levelDesc(l: Level) {
  return t(`lvl${l}desc` as Key)
}

