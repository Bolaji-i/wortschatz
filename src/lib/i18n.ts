const MESSAGES: Record<UiLang, Messages> = { de, en }
type Key = { [K in keyof Messages]: Messages[K] extends string ? K : never }[keyof Messages]

export const lang = computed<UiLang>(() => (state.settings.uiLang === 'en' ? 'en' : 'de'))

export function t(key: Key, params: Record<string, string | number> = {}): string {
  const text = (MESSAGES[lang.value][key] ?? de[key] ?? key) as string
  return text.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : `{${k}}`))
}

export function tList(key: 'promptsEasy' | 'promptsHard'): string[] {
  return MESSAGES[lang.value][key]
}

