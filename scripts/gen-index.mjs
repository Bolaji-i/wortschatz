// Regenerates src/data/words.ts from the files in src/data/lists.
// File names start with the level: a1-*.ts, a2-*.ts, b1-*.ts, … c2-*.ts.
// Files named "<level>-core.ts" are taught first; the rest are mixed in turn.
// Run automatically by `npm run build` and `npm run check-words`.
import { readdirSync, writeFileSync } from 'node:fs'

const LEVELS = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2']
const dir = new URL('../src/data/lists/', import.meta.url)
const files = readdirSync(dir).filter(f => /^[abc][12]-[a-z0-9-]+\.ts$/.test(f)).sort((a, b) => {
  const core = f => (f.endsWith('-core.ts') ? 0 : 1)
  return a.slice(0, 2).localeCompare(b.slice(0, 2)) || core(a) - core(b) || a.localeCompare(b)
})
const ident = f => 'l_' + f.replace(/\.ts$/, '').replace(/-/g, '_')
const byLevel = Object.fromEntries(LEVELS.map(l => [l, files.filter(f => f.slice(0, 2).toUpperCase() === l)]))

const out = `/**
 * Super Wortschatz word bank – A1 to C2.
 * GENERATED by scripts/gen-index.mjs – don't edit by hand.
 * The words live in ./lists as one-line entries (format explained in ./parse.ts).
 * To add words, append lines to a list file or create a new "<level>-<topic>.ts" file.
 */
import { parseList, type Level, type Word } from './parse.ts'
${files.map(f => `import ${ident(f)} from './lists/${f}'`).join('\n')}

export type { Level, Pos, Article, Word } from './parse.ts'
export { LEVELS } from './parse.ts'

const LISTS: Record<Level, string[]> = {
${LEVELS.map(l => `  ${l}: [${byLevel[l].map(ident).join(', ')}]`).join(',\n')}
}

/** Core words first, then the topic lists taken in turns so every day mixes topics. */
function teachingOrder(level: Level): Word[] {
  const lists = LISTS[level].map(src => parseList(src, level))
  const out: Word[] = []
  const max = Math.max(0, ...lists.map(l => l.length))
  const core = ${JSON.stringify(Object.fromEntries(LEVELS.map(l => [l, byLevel[l][0]?.endsWith('-core.ts') ?? false])))}[level]
  if (core && lists.length) out.push(...lists.shift()!)
  for (let i = 0; i < max; i++) for (const l of lists) if (l[i]) out.push(l[i])
  return out
}

/** Words of each level, in teaching order. */
export const WORDS_BY_LEVEL = Object.fromEntries(
  (${JSON.stringify(LEVELS)} as Level[]).map(l => [l, teachingOrder(l)])
) as Record<Level, Word[]>

/** All words (A1 → C2). */
export const WORDS: Word[] = (Object.keys(WORDS_BY_LEVEL) as Level[]).flatMap(l => WORDS_BY_LEVEL[l])

export const WORD_BY_ID: Record<string, Word> = Object.fromEntries(WORDS.map(w => [w.id, w]))

/** Display form, e.g. "die Gefahr". */
export function headword(w: Word) {
  return w.article ? \`\${w.article} \${w.de}\` : w.de
}
`
writeFileSync(new URL('../src/data/words.ts', import.meta.url), out)
console.log(`words.ts: ${files.length} lists`)
